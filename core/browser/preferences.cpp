const SettingSpec *find_setting(const std::string &id) {
    const auto catalog = settings_catalog();
    const auto it =
        std::find_if(catalog.begin(), catalog.end(), [&](const auto &s) { return s.id == id; });
    return it == catalog.end() ? nullptr : &*it;
}
std::string setting_value(const BrowserPreferences &p, const SettingSpec &s) {
    return std::visit(
        [&](auto member) -> std::string {
            using T = std::decay_t<decltype(p.*member)>;
            if constexpr (std::is_same_v<T, std::string>)
                return p.*member;
            else if constexpr (std::is_same_v<T, bool>)
                return p.*member ? "true" : "false";
            else
                return std::to_string(p.*member);
        },
        s.member);
}
bool set_setting(BrowserPreferences &p, const SettingSpec &s, const std::string &value) {
    if (s.kind == SettingKind::Choice &&
        std::none_of(s.choices.begin(), s.choices.end(), [&](auto &c) { return c.value == value; }))
        return false;
    return std::visit(
        [&](auto member) {
            using T = std::decay_t<decltype(p.*member)>;
            if constexpr (std::is_same_v<T, bool>) {
                if (value != "true" && value != "false")
                    return false;
                p.*member = value == "true";
            } else if constexpr (std::is_same_v<T, int>) {
                int n = 0;
                const auto parsed = std::from_chars(value.data(), value.data() + value.size(), n);
                if (parsed.ec != std::errc{} || parsed.ptr != value.data() + value.size())
                    return false;
                if (s.kind == SettingKind::Themes && (n < 0 || n > 5))
                    return false;
                if (s.kind == SettingKind::Number &&
                    (n < s.minimum || n > s.maximum || (n - s.minimum) % s.step != 0))
                    return false;
                p.*member = n;
            } else {
                if (value.size() > 4096 || value.find_first_of("\r\n\t") != std::string::npos)
                    return false;
                if (s.id == "ntp_image_path" && !value.empty() &&
                    !std::filesystem::path(value).is_absolute())
                    return false;
                if ((s.id == "ntp_title" || s.id == "ntp_subtitle") &&
                    std::count_if(value.begin(), value.end(), [](unsigned char c) {
                        return (c & 0xc0) != 0x80;
                    }) > (s.id == "ntp_title" ? 120 : 240))
                    return false;
                if (s.id == "home_page" && !valid_home_address(value))
                    return false;
                if (s.id == "download_directory" && !value.empty() &&
                    !std::filesystem::path(value).is_absolute())
                    return false;
                p.*member = value;
            }
            return true;
        },
        s.member);
}
