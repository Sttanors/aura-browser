std::string translate(std::string_view language, std::string_view english) {
    if (language == "ru") {
        auto it = std::find_if(std::begin(catalog), std::end(catalog),
                               [&](const auto &entry) { return entry.english == english; });
        if (it != std::end(catalog))
            return std::string(it->russian);
    }
    return std::string(english);
}
