"""Regenerate checked-in OS assets and embedded UI/window data from the SVG master.
Requires ImageMagick convert and Pillow; normal browser builds need neither.
"""
from pathlib import Path
import json
import xml.etree.ElementTree as ET
import subprocess
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
folder = ROOT/'resources/branding'
subprocess.run(['convert', '-background', 'none', str(folder/'aura.svg'), '-resize', '512x512', str(folder/'aura.png')], check=True)
image = Image.open(folder/'aura.png').convert('RGBA')
image.save(folder/'aura.png', optimize=True)
image.save(folder/'aura.ico', sizes=[(s,s) for s in (16,24,32,48,64,128,256)])
pixels = list(image.resize((64,64), Image.Resampling.LANCZOS).getdata())
header = '#pragma once\n// Generated by scripts/generate_branding.py from resources/branding/aura.svg.\n#include <cstdint>\nnamespace aura::brand {\n'
header += 'struct Path { const char *data; uint32_t color; float stroke; };\ninline constexpr Path paths[] = {\n'
for path in ET.parse(folder/'aura.svg').getroot().findall('{http://www.w3.org/2000/svg}path'):
    stroke = path.get('stroke-width', '0')
    color = path.get('stroke') if float(stroke) else path.get('fill')
    header += '{'+json.dumps(path.get('d'))+',0xff'+color[1:]+','+stroke+'},\n'
header += '};\ninline constexpr uint32_t argb[] = {\n'
for i in range(0,len(pixels),8):
    header += ','.join(f'0x{a:02x}{r:02x}{g:02x}{b:02x}' for r,g,b,a in pixels[i:i+8])+',\n'
header += '};\n}\n'
(ROOT/'common/branding_data.hpp').write_text(header)
